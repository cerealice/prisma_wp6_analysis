png_files <- sort(list.files(graphs_dir, pattern = "\\.png$", full.names = FALSE))

make_status_rows <- function() {
  sapply(run_results, function(r) {
    cls   <- if (r$status == "ok") "ok" else "error"
    sym   <- if (r$status == "ok") "\u2713" else "\u2717"
    desc  <- if (!is.null(fig_descriptions[[r$script]])) fig_descriptions[[r$script]] else r$script
    t_str <- if (!is.na(r$elapsed)) paste0(" (", r$elapsed, "s)") else ""
    e_str <- if (!is.na(r$error))
      paste0("<br><span class='err-detail'>", gsub("&", "&amp;", gsub("<", "&lt;", r$error)), "</span>")
    else ""
    paste0("<tr class='", cls, "'><td>", sym, " ", r$script, t_str, "</td><td>", desc, e_str, "</td></tr>")
  }, USE.NAMES = FALSE)
}

make_gallery_cards <- function() {
  sapply(png_files, function(f) {
    desc <- if (!is.null(png_descriptions[[f]])) png_descriptions[[f]] else f
    fi   <- tryCatch(file.info(file.path(graphs_dir, f)), error = function(e) NULL)
    size <- if (!is.null(fi) && !is.na(fi$size)) paste0(round(fi$size / 1024), " KB") else ""
    meta <- if (nchar(size) > 0) paste0(f, " \u00b7 ", size) else f
    paste0(
      "<div class='card'>",
      "<a href='", f, "' target='_blank'><img src='", f, "' alt='", f, "' loading='lazy'></a>",
      "<div class='card-body'>",
      "<div class='card-title'>", desc, "</div>",
      "<div class='card-meta'>", meta, "</div>",
      "</div></div>"
    )
  }, USE.NAMES = FALSE)
}

