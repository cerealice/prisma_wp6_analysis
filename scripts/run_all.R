local({
  nb_path <- file.path(scripts_dir, "fig_sm1.ipynb")
  if (!file.exists(nb_path)) {
    message("  Notebook not found: ", nb_path); return(invisible(NULL))
  }
  t0 <- proc.time()
  jupyter_exe <- "C:/Users/Dibella/miniconda3/envs/pypsa-eur/Scripts/jupyter.exe"
  status <- suppressWarnings(
    tryCatch(
      system2(jupyter_exe,
              args    = c("nbconvert", "--to", "notebook",
                          "--execute", "--inplace",
                          "--ExecutePreprocessor.timeout=600",
                          shQuote(normalizePath(nb_path, winslash = "/"))),
              stdout  = TRUE, stderr = TRUE),
      error = function(e) { message("  jupyter not found: ", conditionMessage(e)); NULL }
    )
  )
  elapsed   <- round((proc.time() - t0)[["elapsed"]], 1)
  exit_code <- attr(status, "status")
  if (is.null(status)) {
    message("  Could not run notebook (jupyter not in PATH).")
  } else if (!is.null(exit_code) && exit_code != 0L) {
    message("  Notebook execution FAILED (exit code ", exit_code, "):")
    message(paste(tail(status, 40), collapse = "\n"))
  } else {
    message("  Done (", elapsed, "s)")
  }
})

# ── Run each R figure script ───────────────────────────────────
run_results <- list()

for (script in fig_scripts) {
  path <- file.path(scripts_dir, script)
  if (!file.exists(path)) {
    message("Skipping (not found): ", script)
    run_results[[script]] <- list(script = script, status = "not found",
                                  elapsed = NA_real_, error = NA_character_)
    next
  }

  message("\n", strrep("\u2550", 60))
  message("Running: ", script)
  if (!is.null(fig_descriptions[[script]]))
    message("  ", fig_descriptions[[script]])
  message(strrep("\u2550", 60))

  t0  <- proc.time()
  err <- tryCatch(
    { source(path, local = FALSE); NA_character_ },
    error = function(e) conditionMessage(e)
  )
  elapsed <- round((proc.time() - t0)[["elapsed"]], 1)

  run_results[[script]] <- list(
    script  = script,
    status  = if (is.na(err)) "ok" else "error",
    elapsed = elapsed,
    error   = err
  )

  if (is.na(err)) message("  \u2713 Done (", elapsed, "s)")
  else            message("  \u2717 ERROR: ", err)
}

# ── Build HTML summary ─────────────────────────────────────────
